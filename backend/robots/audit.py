"""
Compare crawler requests with robots.txt, and generate robots.txt rules by
crawler purpose.
"""
from collections import defaultdict
from datetime import date
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

from enrichment.taxonomy import CATEGORIES, all_crawlers, get_crawler_info

from .parser import RobotsTxt

# Operators describe these as acting for a person, and several say robots.txt
# doesn't apply to them, so fetching a disallowed page isn't counted as a violation.
NOT_BOUND_CATEGORIES = {"user_action"}

# Names in the taxonomy that aren't real robots.txt tokens
NOT_TOKENS = {"meta ai", "llama-bot", "metagpt", "claude-web", "anthropic-ai", "anthropic-ai-crawler"}


def audit(robots_text: str, rows: Iterable[Tuple[str, str, Optional[str], int]],
          top_paths: int = 5) -> Dict[str, Any]:
    """
    Args:
        robots_text: contents of robots.txt
        rows: (crawler_name, path, verification, request_count) aggregates
    """
    robots = RobotsTxt(robots_text)
    crawlers: Dict[str, Dict[str, Any]] = {}
    blocked_paths: Dict[str, Dict[str, int]] = defaultdict(lambda: defaultdict(int))
    group_cache: Dict[str, Tuple[Optional[str], list]] = {}

    for crawler_name, path, verification, count in rows:
        if not crawler_name:
            continue
        key = crawler_name.lower()
        if key not in group_cache:
            group_cache[key] = robots.group_for(crawler_name)
        group, rules = group_cache[key]

        entry = crawlers.get(key)
        if entry is None:
            info = get_crawler_info(crawler_name)
            category = info.category if info else None
            entry = crawlers[key] = {
                "crawler_name": info.name if info else crawler_name,
                "operator": info.operator if info else None,
                "category": category,
                "bound_by_robots": category not in NOT_BOUND_CATEGORIES,
                "robots_group": group,
                "requests": 0,
                "blocked_requests": 0,
                "blocked_verified": 0,
                "blocked_suspicious": 0,
                "blocked_unknown": 0,
                "robots_txt_requests": 0,
            }
        entry["requests"] += count
        if (path or "").split("?")[0] == "/robots.txt":
            entry["robots_txt_requests"] += count
        allowed, _ = robots.evaluate(rules, path or "/")
        if not allowed:
            entry["blocked_requests"] += count
            bucket = {"verified": "blocked_verified", "suspicious": "blocked_suspicious"}.get(
                verification or "", "blocked_unknown")
            entry[bucket] += count
            blocked_paths[key][path] += count

    result = []
    for key, entry in crawlers.items():
        paths = sorted(blocked_paths[key].items(), key=lambda kv: -kv[1])[:top_paths]
        entry["top_blocked_paths"] = [{"path": p, "requests": c} for p, c in paths]
        entry["violation"] = entry["bound_by_robots"] and entry["blocked_verified"] > 0
        result.append(entry)
    result.sort(key=lambda e: (-e["blocked_requests"], -e["requests"]))

    bound = [e for e in result if e["bound_by_robots"]]
    return {
        "crawlers": result,
        "summary": {
            "crawlers": len(result),
            "requests": sum(e["requests"] for e in result),
            "blocked_requests": sum(e["blocked_requests"] for e in result),
            "violating_crawlers": sum(1 for e in result if e["violation"]),
            "verified_violations": sum(e["blocked_verified"] for e in bound),
            "spoofed_blocked": sum(e["blocked_suspicious"] for e in result),
        },
        "robots": {
            "agents": robots.agents(),
            "sitemaps": robots.sitemaps,
        },
    }


def generate(block_categories: Sequence[str], extra_disallow: Sequence[str] = ()) -> Dict[str, str]:
    """
    robots.txt rules that block every known crawler in the chosen categories,
    plus an nginx snippet for crawlers that ignore robots.txt.
    """
    unknown = set(block_categories) - set(CATEGORIES)
    if unknown:
        raise ValueError(f"Unknown categories: {', '.join(sorted(unknown))}")

    lines: List[str] = [f"# Generated by Crawlytics on {date.today().isoformat()}"]
    blocked_tokens: List[str] = []
    for category in block_categories:
        tokens = sorted(
            {c.name for c in all_crawlers() if c.category == category and c.name.lower() not in NOT_TOKENS},
            key=str.lower,
        )
        if not tokens:
            continue
        lines.append("")
        lines.append(f"# {CATEGORIES[category]}")
        if category in NOT_BOUND_CATEGORIES:
            lines.append("# Note: user-triggered fetchers may not follow robots.txt; use the server rule below too.")
        lines.extend(f"User-agent: {t}" for t in tokens)
        lines.append("Disallow: /")
        blocked_tokens.extend(tokens)

    if extra_disallow:
        lines.append("")
        lines.append("User-agent: *")
        lines.extend(f"Disallow: {p}" for p in extra_disallow)

    alternation = "|".join(t.replace(" ", "\\ ") for t in blocked_tokens)
    nginx = (
        "# Inside your nginx server { } block: refuse these crawlers outright\n"
        f'if ($http_user_agent ~* "({alternation})") {{\n    return 403;\n}}'
        if blocked_tokens else ""
    )
    return {"robots_txt": "\n".join(lines) + "\n", "nginx": nginx}
